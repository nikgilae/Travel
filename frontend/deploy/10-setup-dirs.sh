#!/usr/bin/env bash
# Шаг 1 — ВЫПОЛНЯТЬ НА СЕРВЕРЕ (ты уже там, в SSH-сессии).
#
# Создаёт структуру каталогов под релизы фронта:
#   /var/www/tourrhythm.ru/releases/<таймстемп>/   — сюда деплой-скрипт
#                                                     заливает новую сборку
#   /var/www/tourrhythm.ru/current                 — симлинк на актуальный
#                                                     релиз, на него смотрит nginx
#
# Почему через symlink, а не прямая перезапись файлов:
# rsync с перезаписью в одну папку даёт окно в несколько сотен мс, когда
# часть файлов уже новые, часть ещё старые (index.html может успеть
# обновиться раньше, чем догрузится новый /assets/*.js — тогда браузер
# запросит хэш файла, которого ещё нет). Symlink переключается одной
# атомарной операцией (ln -sfn), такого окна нет.
# Дополнительный бонус: откат на предыдущий релиз — это одна команда,
# без пересборки и без повторной заливки.

set -euo pipefail

BASE=/var/www/tourrhythm.ru

mkdir -p "$BASE/releases"
chown -R www-data:www-data "$BASE"
chmod 755 "$BASE"

echo "Готово. Структура:"
ls -la "$BASE"
